const { chromium } = require("playwright");
const path = require("node:path");
const OUT = path.join(__dirname, "..", "docs", "v1.2.15");
(async () => {
  const b = await chromium.launch({ channel: "chrome", headless: true });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  await p.goto("https://erp.aibuild.work", { waitUntil: "networkidle", timeout: 60000 });
  await p.waitForTimeout(1200);
  await p.fill('input[name="username"]', "admin");
  await p.fill('input[name="password"]', "123456");
  await p.click("#lbtn");
  await p.waitForSelector("#pwdBtn", { timeout: 40000 });
  await p.click('button[data-go="approvals"]');
  await p.waitForSelector("#body .panel-h", { timeout: 30000 });
  await p.waitForTimeout(1200);
  await p.screenshot({ path: path.join(OUT, "01-待审批已清空.png"), fullPage: true });
  await p.click('[data-v="all"]');
  await p.waitForTimeout(1800);
  await p.screenshot({ path: path.join(OUT, "02-全部审批-两条已带结论.png"), fullPage: true });
  await b.close();
  console.log("done");
})().catch((e) => { console.error(e); process.exit(1); });
